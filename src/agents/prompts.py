def build_agent_user_prompt(
    target: DesignTarget,
    allowed_groups: List[Dict[str, Any]],
    failures: List[FailureFeedbackItem]
) -> str:
    """Build dynamic user prompt containing target specs and active learning failure log."""
    groups_list = "\n".join([f"- {g['name']} ({g['formula']}): {g['description']}" for g in allowed_groups[:8]])
    
    failure_section = ""
    if failures:
        failure_section = "\n### CRITICAL: Previous Failures to Avoid (Active Learning Feedback):\n"
        for idx, f in enumerate(failures, 1):
            failure_section += f"{idx}. Candidate '{f.candidate_name}' (SMILES: `{f.smiles}`) FAILED at [{f.failure_stage}]: {f.reason}\n"
        failure_section += "Do NOT repeat these structures or errors! Modify substitutions to resolve these issues.\n"

    prompt = f"""### Current Design Target:
- Separation: {target.target_gas_pair} (T={target.temperature_k} K, P={target.pressure_bar} bar)
- Feed composition: CO2={target.co2_fraction*100:.0f}%, CH4={target.ch4_fraction*100:.0f}%
- Geometric requirement: PLD >= {target.min_pld_angstrom} Angstrom
- Minimum desired selectivity: >= {target.target_selectivity}

### Allowed Functional Group Pool:
{groups_list}
{failure_section}
Propose an innovative and chemically viable linker modification on the BDC scaffold. Return ONLY the JSON object.
"""
    return prompt
