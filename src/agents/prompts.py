"""Pydantic Schemas and System Prompts for Chemist Agents.

Defines structured data contracts for:
- Design targets (CO2/CH4, T, P)
- Linker modification proposals
- Active learning failure feedback
"""

from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class DesignTarget(BaseModel):
    """Adsorption and screening target constraints."""
    target_gas_pair: str = Field(default="CO2/CH4", description="Gas mixture pair to separate")
    temperature_k: float = Field(default=298.15, description="Operating temperature in Kelvin")
    pressure_bar: float = Field(default=1.0, description="Operating pressure in bar")
    co2_fraction: float = Field(default=0.50, description="Feed mole fraction of CO2")
    ch4_fraction: float = Field(default=0.50, description="Feed mole fraction of CH4")
    min_pld_angstrom: float = Field(default=3.8, description="Pore Limiting Diameter cutoff for CH4 diffusion")
    target_selectivity: float = Field(default=10.0, description="Desired minimum CO2/CH4 selectivity")


class FunctionalGroupSub(BaseModel):
    """Specification of a single functional group substitution."""
    group_name: str = Field(description="Name of the functional group (e.g. -NH2, -OH, -F, -NO2)")
    smiles: str = Field(description="SMILES of the functional group attached")
    position: str = Field(description="Substituted position on BDC ring (e.g. '2', '5', '2,5')")
    rationale: str = Field(description="Chemical rationale for this specific substitution")


class ModificationProposal(BaseModel):
    """Proposal generated by Chemist Agent for linker modification."""
    candidate_name: str = Field(description="Descriptive identifier (e.g. MOF-5-NH2-C2)")
    base_scaffold: str = Field(default="MOF-5 (Zn4O + BDC, pcu)", description="Base scaffold framework")
    modified_linker_smiles: str = Field(description="Canonical neutral SMILES of the modified dicarboxylic acid linker")
    functional_groups: List[FunctionalGroupSub] = Field(description="List of attached functional groups")
    chemical_hypothesis: str = Field(description="Hypothesis explaining why this modification improves CO2 affinity/selectivity while maintaining PLD >= 3.8 A")


class FailureFeedbackItem(BaseModel):
    """Feedback item from previous failed trials for active learning."""
    candidate_name: str
    smiles: str
    failure_stage: str # 'rdkit_validation', 'zeo_pore_screening', 'simulation'
    reason: str


